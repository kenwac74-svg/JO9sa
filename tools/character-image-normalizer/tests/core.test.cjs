const assert = require('node:assert/strict');
const C = require('../src/core.js');
assert.deepEqual(C.alignBounds({x:20,y:40,w:100,h:300},1,24), {s:1,x:327.5,y:-16});
let t=C.fitLandmarks({x:400,y:14},{x:400,y:410},24);
assert(Math.abs(t.s-572/396)<1e-9);
assert(Math.abs(t.s*14+t.y-24)<1e-9);
assert(Math.abs(t.s*410+t.y-596)<1e-9);
assert.throws(()=>C.fitLandmarks({x:0,y:100},{x:0,y:100},24));
let base=new Uint8ClampedArray([20,30,40,255, 0,0,0,0, 9,8,7,128]);
let ai=new Uint8ClampedArray([200,201,202,255, 50,60,70,255, 80,90,100,255]);
let out=C.mergePixels(base,ai,3,1,{x:0,y:0,w:3,h:1});
assert.deepEqual([...out],[20,30,40,255,50,60,70,255,9,8,7,128]);
assert.deepEqual([...C.mergePixels(base,ai,3,1,{x:0,y:0,w:1,h:1})],[...base]);
assert.equal(C.safeName('../bad\\x.png'),'bad_x.png');
assert.equal(C.crc32(new TextEncoder().encode('123456789')),0xcbf43926);
let z=C.zipStore([{name:'a.txt',bytes:new TextEncoder().encode('abc')}]);
assert.equal(new DataView(z.buffer).getUint32(0,true),0x04034b50);
assert.equal(C.checkTransform({s:1,x:0,y:0}),true);
assert.throws(()=>C.checkTransform({s:NaN,x:0,y:0}));
console.log('core: 12 assertions passed');
