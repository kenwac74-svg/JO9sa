'use strict';
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const core = require('C:/Users/Ken Choung/Documents/Codex/2026-10-06/task/JO9sa/tools/text-workshop/core.cjs');
const { checkSyntax } = require('./check-image-cycle-syntax.cjs');
const target = 'C:/MOVE/Jack O Nine Tails v2.3 Kor_nosex/game/jack.qsp';
const raw = fs.readFileSync(target), doc = core.parse(raw);
assert.ok(core.serialize(doc).equals(raw), 'QSP roundtrip mismatch');
const location = doc.locations.find(loc => loc.name === 'interior_change');
assert.ok(location);
const body = core.shift(doc.lines[location.body], 5);
const old = 'id="jo9_image_cycle" style="position:absolute;right:7px;top:4px;';
const next = 'id="jo9_image_cycle" style="position:absolute;left:7px;right:auto;top:4px;';
assert.equal(body.split(old).length - 1, 1);
const changed = body.replace(old, next);
assert.ok(checkSyntax(changed.slice(0, changed.indexOf('!Move to a different room in your apartment'))).ok, 'Handler syntax validation failed');
doc.lines[location.body] = core.shift(changed, -5);
const candidate = core.serialize(doc);
assert.ok(core.serialize(core.parse(candidate)).equals(candidate));
const parsedBefore = core.parse(raw), parsedAfter = core.parse(candidate);
assert.equal(parsedBefore.lines.length, parsedAfter.lines.length);
for (let i = 0; i < parsedBefore.lines.length; i++) if (i !== location.body) assert.equal(parsedAfter.lines[i], parsedBefore.lines[i]);
const mod = { id: '2026-10-08_image_cycle_top_left', description: '돈 표시와 겹치지 않도록 이미지 전환 버튼을 이미지 영역 좌측 상단으로 이동', before_sha256: core.hash(raw), after_sha256: core.hash(candidate), edits: [{ location: 'interior_change', field: 'body', old, new: next, count: 1 }] };
const modsDir = path.join(root, 'tmp/image-cycle-position');
fs.mkdirSync(modsDir, { recursive: true });
fs.writeFileSync(path.join(modsDir, mod.id + '.json'), JSON.stringify(mod, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'mods', mod.id + '.json'), JSON.stringify(mod, null, 2) + '\n');
fs.writeFileSync(path.join(modsDir, 'candidate.qsp'), candidate);
