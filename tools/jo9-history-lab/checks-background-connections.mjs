import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildCoherentConnections,applyCoherentConnections,COHERENT_CONNECTIONS_VERSION} from './dist/background-connections.mjs';
import {applyBackgroundDefaults,backgroundConnectionDefault} from './dist/background-defaults.mjs';
import {defaultConfig,clone,defaultCharacter,validateState,SCHEMA} from './dist/engine.mjs';
import {buildBackgroundCases,findBackgrounds} from './dist/backgrounds.mjs';
const base=JSON.parse(fs.readFileSync('dist/data/backgrounds.json'));
const catalogue={...base,records:[...base.records,...JSON.parse(fs.readFileSync('dist/data/background-drafts.json')).records]};
const links=buildCoherentConnections(catalogue);
const config=defaultConfig();config.backgroundSettings.links=clone(links);
config.backgroundSettings.defaultConnectionsVersion=COHERENT_CONNECTIONS_VERSION;
const cases=buildBackgroundCases(catalogue,config);
const has=(world,occupation,family)=>findBackgrounds(cases,{world,occupation,...family?{family}:{}}).length>0;
for(const world of ['prehistoric','barbarian','sns','medieval','darkfantasy','highfantasy','steampunk','industrial','modern','cyberpunk','utopia','darkfuture','space','earth_rome'])assert(cases.some(r=>r.world.id===world));
for(const id of new Set(catalogue.records.filter(r=>r.kind==='family').map(r=>r.id)))assert(cases.some(r=>r.family.id===id),'reachable family: '+id);
for(const id of new Set(catalogue.records.filter(r=>r.kind==='occupation').map(r=>r.id)))assert(cases.some(r=>r.occupation.id===id),'reachable occupation: '+id);
for(const job of ['academy','mech','contraband','astrofarmer','installer']){
 assert(has('space',job));
 assert(cases.filter(r=>r.occupation.id===job).every(r=>r.world.id==='space'));
}
for(const job of ['mind_contol','jailer','anter'])assert(cases.filter(r=>r.occupation.id===job).every(r=>r.world.id==='darkfuture'));
assert(!has('cyberpunk','astrofarmer'));
assert(!has('medieval','sorceress'));assert(has('highfantasy','sorceress'));
assert(!has('earth_rome','noble_wife'));assert(!has('earth_rome','valertry'));
assert(!has('modern','mprincess'));assert(!has('medieval','mprincess','orphan'));
assert(has('medieval','mprincess','mprincess'));assert(has('barbarian','barbarian_princess','barbarian_king'));
assert(!has('prehistoric','freaser'));assert(!has('medieval','weaver'));assert(has('industrial','freaser'));
assert(!has('utopia','thief'));assert(!has('utopia','policewoman'));assert(!has('utopia','beggar'));
assert(has('utopia','writer'));assert(has('utopia','teacher'));
assert(!has('industrial','hacker'));assert(has('modern','hacker'));
assert(!has('industrial','former_slave'));assert(has('earth_rome','former_slave'));
assert(!has('medieval','beggar','mprincess'));assert(has('medieval','beggar','orphan'));
assert(has('modern','student','worker'),'education not automatically barred by income');
assert(has('space','nurse','asteroid'),'training can change profession without changing origin');
const fresh=defaultConfig();applyBackgroundDefaults(fresh,catalogue);
assert(JSON.stringify(fresh.backgroundSettings.links)===JSON.stringify(links),'fresh defaults must use coherent graph, not legacy union');
assert.equal(fresh.backgroundSettings.defaultConnectionsVersion,COHERENT_CONNECTIONS_VERSION);
const before=clone(fresh);assert.equal(applyBackgroundDefaults(fresh,catalogue),false);assert.deepEqual(fresh,before);
fresh.backgroundSettings.links.worldOccupations.space=[];assert.equal(applyBackgroundDefaults(fresh,catalogue),false);
assert.deepEqual(fresh.backgroundSettings.links.worldOccupations.space,[],'later manual edits survive');
assert(backgroundConnectionDefault(fresh,catalogue,'worldOccupations','space').includes('installer'));
assert.deepEqual(fresh.backgroundSettings.links.worldOccupations.space,[]);
const backup=validateState({schema:SCHEMA,config,character:defaultCharacter(),snapshots:[]});
assert.deepEqual(backup.config.backgroundSettings.links,links);
const personalized=defaultConfig();
personalized.backgroundSettings.texts.occupation.thief='개인 수정 대사';
personalized.backgroundSettings.ageRules.occupation.mafia_boss={required:[2],rejected:[0,1]};
personalized.backgroundModifiers.occupation.thief={intimacy:1.7,combat:1,ranges:{}};
const saved=clone(personalized);applyCoherentConnections(personalized,catalogue);
const restored=clone(personalized);
restored.backgroundSettings.links=saved.backgroundSettings.links;
for(const kind of ['world','family','occupation'])for(const id of Object.keys(restored.backgroundSettings.ageRules[kind]))if(!Object.hasOwn(saved.backgroundSettings.ageRules[kind],id))delete restored.backgroundSettings.ageRules[kind][id];
if(saved.backgroundSettings.defaultConnectionsVersion===undefined)delete restored.backgroundSettings.defaultConnectionsVersion;
else restored.backgroundSettings.defaultConnectionsVersion=saved.backgroundSettings.defaultConnectionsVersion;
assert.deepEqual(restored,saved,'explicit application preserves prose, numbers and existing ages; fills only newly connected age defaults');
assert.deepEqual(personalized.backgroundSettings.ageRules.occupation.schoolgirl,{required:[0],rejected:[]});
assert.deepEqual(personalized.backgroundSettings.ageRules.occupation.tribal_girl,{required:[0],rejected:[]});
const legacy=defaultConfig();legacy.backgroundSettings.defaultConnectionsVersion='20261111-v1';
legacy.backgroundSettings.links.worldOccupations.space=['installer'];const old=clone(legacy);
assert.equal(applyBackgroundDefaults(legacy,catalogue),false);assert.deepEqual(legacy,old,'existing browser edits wait for explicit application');
console.log('PASS · coherent 14-world graph; every existing origin/job reachable; technology, status, poverty, utopia, magic and slavery constraints; editable defaults and backup round trip · '+cases.length+' combinations');
