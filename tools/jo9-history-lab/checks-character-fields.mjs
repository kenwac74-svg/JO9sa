import assert from 'node:assert/strict';
import fs from 'node:fs';
import {BASE_FIELD_ORDER,orderCharacterJSON,describeCharacterField} from './dist/character-fields.mjs';
import {parseCharacterJSON,exportCharacterJSON,primitiveFields} from './dist/character-io.mjs';
import {freshState} from './dist/engine.mjs';
const template=['fullimage','fullmade','fullmistress','fullsecretary','seed_ava','seed_ava_gray','seed_ava_clear','seed_age','seed_boobs','seed_boobs_img','seed_pussy_img','seed_psy_basic','seed_world','bathing_alone','singing','cooking','cleaning','dance','enchanting','percussion','fighting','woodwind','gymnastics','lesbo_bath','music','nurse','piano','rest','secretary','student','painting'];
assert.deepEqual(BASE_FIELD_ORDER,template);
const original={custom_z:1,...Object.fromEntries([...template].reverse().map(k=>[k,k])),custom_a:2};
const working={new_tail:3,...original};
const ordered=orderCharacterJSON(working,original);
assert.deepEqual(Object.keys(ordered),[...template,'custom_z','custom_a','new_tail']);
assert.deepEqual(ordered,working);assert.equal(Object.keys(working)[0],'new_tail');
const nested=orderCharacterJSON({version:1,character:working,other:{music:2,cooking:3}}, {version:1,character:original,other:{music:2,cooking:3}},['character']);
assert.deepEqual(Object.keys(nested.character),Object.keys(ordered));
assert.deepEqual(Object.keys(nested.other),['music','cooking']);
const sample=JSON.parse(fs.readFileSync('dist/data/isabella-source.json'));
const traits=JSON.parse(fs.readFileSync('dist/data/traits.json')).rows;
for(const f of primitiveFields(sample))assert.equal(describeCharacterField(f.path,f.value,traits).confirmed,true,`Missing explanation: ${f.key}`);
assert.match(describeCharacterField(['cooking'],'girls/scene/').description,/画像|이미지/);
assert.match(describeCharacterField(['seed_cook'],3).hint,/0=F/);
assert.match(describeCharacterField(['seed_age'],0).hint,/실제 나이.*아닙니다/);
assert.equal(describeCharacterField(['seed_world'],'').confirmed,false);
assert.equal(describeCharacterField(['custom_future'],7).confirmed,false);
assert.match(describeCharacterField(['music'],'').hint,/무작위/);
const state=freshState(),parsed=parseCharacterJSON(sample,'2571_isabella.json',state.config,traits);
state.character=parsed.character;state.characterFile=parsed.document;
const output=exportCharacterJSON(state);
const present=template.filter(k=>Object.hasOwn(sample,k));
assert.deepEqual(Object.keys(output).slice(0,present.length),present);
assert.equal(output.fullmade,sample.fullmade);assert.equal(output.indpack_info.pack_ver,sample.indpack_info.pack_ver);
assert.deepEqual(JSON.parse(JSON.stringify(output)),output);
for(const path of [['jo9_initial_history','values','wins','value'],['jo9_initial_history','combat_categories','pvp','values','wins','value'],['combatGroups','pvp','wins','value']])assert.match(describeCharacterField(path,3).description,/보존하는 과거|보존하는 이전/);
for(const path of [['jo9_owner_history','combat_categories','pve','values','wins','value'],['ownerCombatGroups','pvp','escapes','value']]){const field=describeCharacterField(path,0);assert.match(field.label,/소속 이후/);assert.match(field.hint,/과거 세계.*추정하지/);}
console.log(`PASS · original template order, unknown-field stability, nested scope, valid JSON export and ${primitiveFields(sample).length} source-field explanations`);
