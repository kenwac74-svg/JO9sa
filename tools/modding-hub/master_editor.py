  for k,v in data.items():
   group='appearance' if k in image_keys or k.startswith(('seed_boobs','seed_pussy')) else 'background' if k in bg_keys else 'stats'
   if k!='seed_name' and group in include:new[k]=copy.deepcopy(v)
  newmaster=copy.deepcopy(master) if 'background' in include or 'stats' in include else {'name':name,'description':'','difficulty':'','statsCode':'','portrait':'','sepia':''}
