 def clone(self,role,sid,body):
  self._check_revision(role,sid,body.get('revision'));r=self.clone_preview(role,sid,body)
  if body.get('dryRun'):return {k:v for k,v in r.items() if k!='talkbook'}
  profile={'data':r['data'],'master':r['master'],'initialOverrides':r['initialOverrides'],'simulation':r['simulation'],'background':r['background'],'source':{'role':role,'id':int(sid)}}
  payloads={self._profile_file(r['role'],r['id']):encoded(profile)}
  for dest,src in r['imageCopies'].items():payloads[self.root/dest]=(self.root/src).read_bytes()
  if r['role']=='slave':
   path=self.root/r['json']
   if path.exists():raise FileExistsError(str(path))
   payloads[path]=encoded(r['data'])
   if r['talkbook']:payloads[self.root/'jo9_talkbook'/(str(r['id'])+'.json')]=encoded({**r['talkbook'],'id':r['id'],'name':r['data']['seed_name'],'jsonFile':path.name})
  else:
   if r['talkbook']:profile['talkbook']=r['talkbook'];payloads[self._profile_file('master',r['id'])]=encoded(profile)
   d,text,_=self._native();extra={}
   if r['initialOverrides']:
    fields=self.initial_catalog(r['master'],overrides=r['initialOverrides'],doc=d)['fields']
    r['master']['statsCode'],extra=initials.apply_overrides(d,r['id'],r['master']['statsCode'],r['initialOverrides'],fields)
    profile['master']=r['master'];payloads[self._profile_file('master',r['id'])]=encoded(profile)
   block='\r\n! JO9 MOD START MASTER_EDITOR_'+str(r['id'])+'\r\n'
   for key,arr in ARRAYS.items():block+=arr+'['+str(r['id'])+'] = '+('{\r\n'+r['master'][key]+'\r\n}' if key=='statsCode' else quote(r['master'][key]))+'\r\n'
   block+='! JO9 MOD END MASTER_EDITOR_'+str(r['id'])+'\r\n';self._qsp_patch(d,text,text+block,payloads,extra)
  self._write(payloads);return {k:v for k,v in r.items() if k!='talkbook'}
 def read_slave_talk(self,sid):
  p=self.root/'jo9_talkbook'/(str(int(sid))+'.json')
  return json.loads(p.read_text('utf-8-sig')) if p.exists() else None
 def talk(self,sid,body=None):
  self.read(sid);p=self._profile('master',sid)
  if body is not None:
   self._check_revision('master',sid,body.get('revision'))
   book=body.get('book')
   if not isinstance(book,dict):raise ValueError('대사집은 객체여야 합니다.')
   if body.get('applyBackground') is True:
    p['data']={**p.get('data',{}),**backgrounds.seed_values(book.get('background',{}))}
    book={**p.get('talkbook',{}),'background':copy.deepcopy(book.get('background',{}))}
   p['talkbook']=book;p['background']=copy.deepcopy(book.get('background',{}));self._write({self._profile_file('master',sid):encoded(p)})
  result={'id':int(sid),'path':self._profile_file('master',sid).relative_to(self.root).as_posix(),'exists':'talkbook' in p,'book':p.get('talkbook'),'revision':self.revision(sid),'noAutoGenerate':False}
  if body is not None and body.get('applyBackground') is True:result['character']=self.read(sid)
  return result
