def statements(text):
 """Physical-line spans with quoted continuations and nested code braces intact."""
 start=i=depth=0;q='';comment=False
 while i<len(text):
  c=text[i]
  if comment:
   if c=='\n':comment=False
   else:i+=1;continue
  elif q:
   if c==q:
    if i+1<len(text) and text[i+1]==q:i+=2;continue
    q=''
  elif c in "'\"":q=c
  elif c=='!':comment=True
  elif c=='{':depth+=1
  elif c=='}':
   depth-=1
   if depth<0:raise ValueError('코드의 닫는 중괄호가 남습니다.')
  if c=='\n' and not q and depth==0 and not text[start:i].rstrip().endswith('_'):
   yield start,i+1,text[start:i+1];start=i+1
  i+=1
 if q or depth:raise ValueError('코드의 따옴표 또는 중괄호가 닫히지 않았습니다.')
 if start<len(text):yield start,len(text),text[start:]

def array_entries(text):
 result={}
 for start,end,s in statements(text):
  match=re.match(r'^\s*(\$\w+)\[(\d+)\]\s*=\s*',s)
  if not match or match[1] not in ARRAYS.values():continue
  value_start=start+match.end();value_end=end
  while value_end>value_start and text[value_end-1].isspace():value_end-=1
  # Array definitions use either strings or a complete code block; retain all raw spans.
  result[(match[1],int(match[2]))]=(value_start,value_end,text[value_start:value_end])
 return result

def literal(raw):
 raw=raw.strip();parts=[];i=0
 while i<len(raw):
  if raw[i].isspace() or raw[i] in '+_':i+=1;continue
  if raw[i]=='!':break
  if raw[i] not in "'\"":raise ValueError('문자열 계산식을 자동 해석할 수 없습니다. 원본 코드로 편집하세요.')
  quote=raw[i];i+=1;part=''
  while i<len(raw):
   if raw[i]==quote:
    if i+1<len(raw) and raw[i+1]==quote:part+=quote;i+=2;continue
    i+=1;break
   part+=raw[i];i+=1
  else:raise ValueError('문자열이 닫히지 않았습니다.')
  parts.append(part)
 return ''.join(parts)
